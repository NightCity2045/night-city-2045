using Content.Client.Stylesheets;
using Content.Shared._NC.Crafting.ArmorWorkbench.Components;
using Content.Shared._NC.Crafting.ArmorWorkbench.Events;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using System.Linq;

namespace Content.Client._NC.Crafting.ArmorWorkbench.UI;

[GenerateTypedNameReferences]
public sealed partial class ArmorWorkbenchWindow : DefaultWindow
{
    private readonly Dictionary<int, NetEntity> _baseItemMap = new();
    private readonly Dictionary<int, NetEntity> _softItemMap = new();
    private readonly Dictionary<int, NetEntity> _hardItemMap = new();
    private NetEntity? _loadedBlueprint;
    private NetEntity? _selectedBaseMaterial;
    private NetEntity? _selectedSoftMaterial;
    private NetEntity? _selectedHardMaterial;
    private float _fade;
    private float _targetFade = 1f;

    public event Action<ArmorWorkbenchLayerSlot, NetEntity>? OnMaterialSelected;
    public event Action<ArmorWorkbenchEjectTarget>? OnEjectRequested;
    public event Action? OnStartCraft;

    public ArmorWorkbenchWindow()
    {
        RobustXamlLoader.Load(this);
        Stylesheet = IoCManager.Resolve<IStylesheetManager>().SheetNightCity;

        BaseMaterialButton.OnItemSelected += args =>
        {
            if (_baseItemMap.TryGetValue(args.Id, out var material))
                OnMaterialSelected?.Invoke(ArmorWorkbenchLayerSlot.Base, material);
        };

        SoftMaterialButton.OnItemSelected += args =>
        {
            if (_softItemMap.TryGetValue(args.Id, out var material))
                OnMaterialSelected?.Invoke(ArmorWorkbenchLayerSlot.Soft, material);
        };

        HardMaterialButton.OnItemSelected += args =>
        {
            if (_hardItemMap.TryGetValue(args.Id, out var material))
                OnMaterialSelected?.Invoke(ArmorWorkbenchLayerSlot.Hard, material);
        };

        AssembleButton.OnPressed += _ => OnStartCraft?.Invoke();
        EjectRecipeButton.OnPressed += _ => OnEjectRequested?.Invoke(ArmorWorkbenchEjectTarget.Blueprint);
        EjectRecipeBottomButton.OnPressed += _ => OnEjectRequested?.Invoke(ArmorWorkbenchEjectTarget.Blueprint);
        EjectMaterialsButton.OnPressed += _ => OnEjectRequested?.Invoke(ArmorWorkbenchEjectTarget.Materials);
    }

    protected override void FrameUpdate(Robust.Shared.Timing.FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // Keep the window feeling responsive without adding expensive effects.
        _fade = MathHelper.Lerp(_fade, _targetFade, args.DeltaSeconds * 10f);
        ModulateSelfOverride = Color.White.WithAlpha(_fade);
    }

    public void UpdateState(ArmorWorkbenchBoundUserInterfaceState state)
    {
        _loadedBlueprint = state.BlueprintEntity;
        _selectedBaseMaterial = state.SelectedBaseMaterial;
        _selectedSoftMaterial = state.SelectedSoftMaterial;
        _selectedHardMaterial = state.SelectedHardMaterial;

        BlueprintLabel.Text = state.BlueprintName ?? Loc.GetString("armor-workbench-window-blueprint-empty");
        ResultLabel.Text = state.ResultName ?? Loc.GetString("armor-workbench-window-result-empty");

        FillOptions(BaseMaterialButton, _baseItemMap, state.BaseMaterials, state.SelectedBaseMaterial);
        FillOptions(SoftMaterialButton, _softItemMap, state.SoftMaterials, state.SelectedSoftMaterial);
        FillOptions(HardMaterialButton, _hardItemMap, state.HardMaterials, state.SelectedHardMaterial);

        BaseForecastLabel.Text = GetBaseForecastText(state.BaseMaterials, state.SelectedBaseMaterial);
        SoftForecastLabel.Text = GetForecastText(
            state.SoftMaterials,
            state.SelectedSoftMaterial,
            "armor-workbench-window-soft-forecast",
            "armor-workbench-window-soft-forecast-empty");

        HardForecastLabel.Text = GetForecastText(
            state.HardMaterials,
            state.SelectedHardMaterial,
            "armor-workbench-window-hard-forecast",
            "armor-workbench-window-hard-forecast-empty");

        StatusLabel.Text = Loc.GetString(GetStatusKey(state.Status));
        StatusLabel.StyleClasses.Clear();
        StatusLabel.StyleClasses.Add(GetStatusClass(state.Status));

        EjectRecipeButton.Disabled = state.IsCrafting || state.BlueprintEntity == null;
        EjectRecipeBottomButton.Disabled = state.IsCrafting || state.BlueprintEntity == null;
        EjectMaterialsButton.Disabled = state.IsCrafting ||
            state.BaseMaterials.Count == 0 && state.SoftMaterials.Count == 0 && state.HardMaterials.Count == 0;
        AssembleButton.Disabled = state.IsCrafting ||
            state.Status is not ArmorWorkbenchUiStatus.Ready;

        if (state.IsCrafting)
        {
            AssembleButton.Text = Loc.GetString("armor-workbench-window-assembling", ("seconds", (int) state.CraftDuration));
        }
        else
        {
            AssembleButton.Text = Loc.GetString("armor-workbench-window-assemble");
        }
    }

    private static string GetBaseForecastText(List<ArmorWorkbenchMaterialEntry> entries, NetEntity? selected)
    {
        if (selected == null)
            return Loc.GetString("armor-workbench-window-base-forecast-empty");

        var entry = entries.FirstOrDefault(x => x.Entity == selected.Value);
        if (entry == null)
            return Loc.GetString("armor-workbench-window-base-forecast-empty");

        return Loc.GetString("armor-workbench-window-base-forecast", ("name", entry.Name));
    }

    private static string GetForecastText(
        List<ArmorWorkbenchMaterialEntry> entries,
        NetEntity? selected,
        string filledKey,
        string emptyKey)
    {
        if (selected == null)
            return Loc.GetString(emptyKey);

        var entry = entries.FirstOrDefault(x => x.Entity == selected.Value);
        if (entry == null)
            return Loc.GetString(emptyKey);

        return Loc.GetString(
            filledKey,
            ("durability", (int) entry.Durability),
            ("armorClass", entry.ArmorClass));
    }

    private void FillOptions(
        OptionButton button,
        Dictionary<int, NetEntity> map,
        List<ArmorWorkbenchMaterialEntry> entries,
        NetEntity? selected)
    {
        button.Clear();
        map.Clear();

        for (var i = 0; i < entries.Count; i++)
        {
            var entry = entries[i];
            button.AddItem(entry.Name, i);
            map[i] = entry.Entity;
        }

        if (selected == null)
            return;

        foreach (var (id, netEntity) in map)
        {
            if (netEntity == selected.Value)
            {
                button.SelectId(id);
                break;
            }
        }
    }

    private static string GetStatusKey(ArmorWorkbenchUiStatus status)
    {
        return status switch
        {
            ArmorWorkbenchUiStatus.MissingBlueprint => "armor-workbench-status-missing-blueprint",
            ArmorWorkbenchUiStatus.MissingBaseMaterial => "armor-workbench-status-missing-base",
            ArmorWorkbenchUiStatus.MissingRecipeMaterials => "armor-workbench-status-missing-materials",
            ArmorWorkbenchUiStatus.Ready => "armor-workbench-status-ready",
            ArmorWorkbenchUiStatus.Crafting => "armor-workbench-status-crafting",
            _ => "armor-workbench-status-waiting"
        };
    }

    private static string GetStatusClass(ArmorWorkbenchUiStatus status)
    {
        return status switch
        {
            ArmorWorkbenchUiStatus.Ready => StyleNightCity.StatusGood,
            ArmorWorkbenchUiStatus.Crafting => StyleNightCity.StatusWarning,
            ArmorWorkbenchUiStatus.MissingBlueprint => StyleNightCity.StatusDanger,
            ArmorWorkbenchUiStatus.MissingBaseMaterial => StyleNightCity.StatusDanger,
            ArmorWorkbenchUiStatus.MissingRecipeMaterials => StyleNightCity.StatusDanger,
            _ => StyleNightCity.StatusWarning
        };
    }
}
